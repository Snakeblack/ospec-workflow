const HERE = dirname(fileURLToPath(import.meta.url));

/** "ospec-workflow" | "@org/ospec-workflow" -> "Ospec-Workflow" */
function titleCaseName(name) {
  const bare = name.includes("/") ? name.split("/").pop() : name;
  return bare
    .split("-")
    .map((seg) => (seg ? seg.charAt(0).toUpperCase() + seg.slice(1) : seg))
    .join("-");
}

// Site title: the parent repository's package.json name, falling back to the
// repository directory name, then to a generic label. Never hand-edit here —
// fix the parent package.json instead.
function resolveSiteTitle() {
  try {
    const pkg = JSON.parse(readFileSync(resolve(HERE, "..", "package.json"), "utf8"));
    if (pkg.name) return titleCaseName(pkg.name);
  } catch {
    // No parent package.json (non-Node repo): fall through to the dir name.
  }
  const dir = basename(resolve(HERE, ".."));
  return dir ? titleCaseName(dir) : "Project Documentation";
}

// Sidebar manifest emitted by scripts/sync-handbook.mjs at predev/prebuild
// time from the handbook's handbook.json: language, top links (quickstart
// first) and groups in the manifest's order. null when missing or unreadable.
function readSidebarManifest() {
  try {
    return JSON.parse(readFileSync(resolve(HERE, "src", "sidebar.generated.json"), "utf8"));
  } catch {
    return null;
  }
}

const SIDEBAR_MANIFEST = readSidebarManifest();

// UI language: the handbook's language (handbook.json), carried by the
// sidebar manifest. Starlight ships translated UI strings, so a monolingual
// root locale localizes search, navigation, and <html lang>. Falls back to
// English when the manifest or its language is missing.
function resolveDocLanguage() {
  const lang = SIDEBAR_MANIFEST && SIDEBAR_MANIFEST.language;
  if (typeof lang === "string" && /^[a-z]{2,3}(-[A-Za-z0-9]+)*$/.test(lang)) return lang;
  return "en";
}

/** "es" -> "Español": the language's own name, as the root locale label. */
function localeLabel(lang) {
  try {
    const name = new Intl.DisplayNames([lang], { type: "language" }).of(lang);
    if (name) return name.charAt(0).toLocaleUpperCase(lang) + name.slice(1);
  } catch {
    // Unknown to this runtime's ICU data: use the code itself.
  }
  return lang;
}

const DOC_LANGUAGE = resolveDocLanguage();

// Canonical origin of the published docs (Vercel, site root — no subpath).
const SITE = "https://ospec-workflow.mretamozo.com";

// Sidebar: the quickstart and other top pages first, then one group per
// handbook directory with its label and, when handbook.json declares an
// audience, a text badge. Falls back to Starlight's default autogenerated
// sidebar when the manifest is missing or unreadable.
function resolveSidebar() {
  if (!SIDEBAR_MANIFEST) return undefined;
  try {
    return [
      ...SIDEBAR_MANIFEST.topLinks.map((t) => ({ label: t.label, link: t.link })),
      ...SIDEBAR_MANIFEST.groups.map((g) => ({
        label: g.label,
        ...(g.badge ? { badge: { text: g.badge, variant: "note" } } : {}),
        items: [{ autogenerate: { directory: g.directory } }],
      })),
    ];
  } catch {
    return undefined;
  }
}

